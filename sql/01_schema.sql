-- NOTE: Booking_Value is the booking's quoted value for EVERY status; it is revenue only when Booking_Status = 'Success'.
CREATE DATABASE IF NOT EXISTS ola_ride_insights;
USE ola_ride_insights;

CREATE TABLE IF NOT EXISTS ola_bookings (
  Booking_ID                 VARCHAR(20)  NOT NULL,
  Booking_Status             VARCHAR(25)  NOT NULL,
  Customer_ID                VARCHAR(15)  NOT NULL,
  Vehicle_Type               VARCHAR(20)  NOT NULL,
  Pickup_Location            VARCHAR(60),
  Drop_Location              VARCHAR(60),
  V_TAT                      DECIMAL(6,1) NULL,
  C_TAT                      DECIMAL(6,1) NULL,
  Canceled_Rides_by_Customer VARCHAR(60)  NULL,
  Canceled_Rides_by_Driver   VARCHAR(60)  NULL,
  Incomplete_Rides           VARCHAR(3)   NULL,
  Incomplete_Rides_Reason    VARCHAR(30)  NULL,
  Booking_Value              INT          NOT NULL,
  Payment_Method             VARCHAR(15)  NULL,
  Ride_Distance              INT          NOT NULL,
  Driver_Rating              DECIMAL(2,1) NULL,
  Customer_Rating            DECIMAL(2,1) NULL,
  Booking_Timestamp          DATETIME     NOT NULL,
  PRIMARY KEY (Booking_ID),
  KEY idx_status   (Booking_Status),
  KEY idx_vehicle  (Vehicle_Type, Booking_Status),
  KEY idx_customer (Customer_ID),
  KEY idx_ts       (Booking_Timestamp),
  KEY idx_payment  (Payment_Method),
  CONSTRAINT chk_rating CHECK (Driver_Rating  IS NULL OR Driver_Rating  BETWEEN 1 AND 5),
  CONSTRAINT chk_crate  CHECK (Customer_Rating IS NULL OR Customer_Rating BETWEEN 1 AND 5)
) ENGINE=InnoDB;

